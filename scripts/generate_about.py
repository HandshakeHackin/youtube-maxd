"""Generate native/tube_about_data.h from CHANGELOG.md.

The newest `## version` heading is the application version shown in About, and
every `- ` bullet becomes one bounded changelog row. `--check` verifies that
the committed header is current and that the build and packaging scripts name
the same version, without writing anything.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CHANGELOG = ROOT / "CHANGELOG.md"
OUTPUT = ROOT / "native/tube_about_data.h"
MAX_ROWS = 96
MAX_ROW_BYTES = 300
VERSION = re.compile(r"^## (\d+\.\d+\.\d+)\s*$")


def plain(text):
    """Markdown inline syntax to the plain text a row can show."""
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = text.replace("`", "").replace("**", "")
    return " ".join(text.split())


def parse(markdown):
    rows, version, bullet = [], None, None

    def flush():
        nonlocal bullet
        if bullet is not None:
            rows.append((version, plain(bullet)))
        bullet = None

    for line in markdown.splitlines():
        heading = VERSION.match(line)
        if heading or line.startswith("#") or not line.strip():
            flush()
            if heading:
                version = heading.group(1)
            elif line.startswith("## "):
                raise ValueError(f"Version heading must be '## X.Y.Z': {line!r}")
        elif line.startswith("- "):
            flush()
            if version is None:
                raise ValueError("Bullet before the first version heading")
            bullet = line[2:]
        elif bullet is not None and line.startswith(" "):
            bullet += " " + line.strip()
        else:
            flush()
    flush()
    if not rows:
        raise ValueError("CHANGELOG.md has no version section with bullets")
    versions = list(dict.fromkeys(row[0] for row in rows))
    if versions != sorted(versions, key=lambda v: tuple(map(int, v.split("."))), reverse=True):
        raise ValueError("Versions must be listed newest first")
    if len(rows) > MAX_ROWS:
        raise ValueError(f"More than {MAX_ROWS} changelog rows; drop the oldest sections from the in-app list")
    for _, text in rows:
        if not text or len(text.encode()) > MAX_ROW_BYTES:
            raise ValueError(f"Changelog row must be 1..{MAX_ROW_BYTES} bytes: {text[:60]!r}")
        if any(ord(ch) < 0x20 for ch in text):
            raise ValueError(f"Control character in changelog row: {text[:60]!r}")
    return rows


def c_string(text):
    out = []
    for byte in text.encode():
        if byte in (0x22, 0x5C):
            out.append("\\" + chr(byte))
        elif 0x20 <= byte < 0x7F and byte != 0x3F:
            out.append(chr(byte))
        else:
            out.append(f"\\{byte:03o}")  # also '?', so no trigraph can form
    return '"' + "".join(out) + '"'


def render(rows):
    lines = [
        "// Generated by scripts/generate_about.py from CHANGELOG.md. Do not edit.",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#ifndef TUBE_ABOUT_DATA_H",
        "#define TUBE_ABOUT_DATA_H",
        "",
        f"#define TUBE_ABOUT_CHANGELOG_VERSION {c_string(rows[0][0])}",
        f"#define TUBE_ABOUT_CHANGELOG_ROWS {len(rows)}",
        f"#define TUBE_ABOUT_CHANGELOG_ROW_BYTES {MAX_ROW_BYTES}",
        "",
        "#define TUBE_ABOUT_CHANGELOG_DATA \\",
    ]
    lines += [f"    {{{c_string(version)}, {c_string(text)}}}, \\" for version, text in rows]
    lines[-1] = lines[-1][:-3]
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def check_scripts(version):
    """The version also lives in two script literals; keep them in step."""
    expected = {
        "scripts/prepare_native.py": f'"VERSION").write_text("{version}\\n")',
        "scripts/package_release.py": f'"version": "{version}"',
    }
    return [f"{name} does not name version {version}" for name, needle in expected.items()
            if needle not in (ROOT / name).read_text()]


def main(argv):
    rows = parse(CHANGELOG.read_text(encoding="utf-8"))
    text = render(rows)
    if "--check" in argv:
        problems = check_scripts(rows[0][0])
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            problems.append("native/tube_about_data.h is stale; run scripts/generate_about.py")
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUTPUT.relative_to(ROOT)}: version {rows[0][0]}, {len(rows)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
