"""Render the SmartTube parity tracker; status files are maintained by hand.

Each native/parity/status/*.json item records one SmartTube feature surface:
status is done, partial, missing or not_applicable. "done" means implemented
with offline evidence; console acceptance is tracked in HARDWARE_ACCEPTANCE.md.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUSES = ("done", "partial", "missing", "not_applicable")
AREAS = {"player": "Player and playback", "browse": "Browsing, search and menus",
         "accounts": "Accounts, remote control and integrations", "general": "General, interface and maintenance"}


def load():
    inventory = {item["id"] for item in json.loads((ROOT / "native/parity/smarttube-baseline.json").read_text(encoding="utf-8"))["features"]}
    areas, seen = {}, set()
    for name in AREAS:
        items = json.loads((ROOT / f"native/parity/status/{name}.json").read_text(encoding="utf-8"))["items"]
        for item in items:
            if item["status"] not in STATUSES: raise ValueError(f"{item['id']}: invalid status {item['status']}")
            if item["id"] in seen: raise ValueError(f"{item['id']}: listed twice")
            if not item["id"].startswith("extra.") and item["id"] not in inventory: raise ValueError(f"{item['id']}: not in the baseline inventory")
            if item["status"] == "done" and not item.get("ps5_evidence"): raise ValueError(f"{item['id']}: done without evidence")
            if item["status"] in ("partial", "missing") and not item.get("gaps"): raise ValueError(f"{item['id']}: open item without a stated gap")
            seen.add(item["id"])
        areas[name] = items
    absent = sorted(inventory - seen)
    if absent: raise ValueError("Inventory entries without a status: " + ", ".join(absent))
    return areas


def cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def render(areas):
    lines = ["# SmartTube parity tracker", "",
             "Generated by `scripts/parity_report.py` from `native/parity/status/*.json`; edit those files, not this one.",
             "Baseline: SmartTube `2c60453007dfc3775ff525c3837c2d1d4e95aab9`. **Done** means implemented with offline",
             "evidence; console acceptance is recorded separately in [hardware acceptance](HARDWARE_ACCEPTANCE.md).",
             "**Offline** marks open items that can be implemented and host-tested without a console.", "",
             "| Area | Done | Partial | Missing | Not applicable | Total |", "| --- | ---: | ---: | ---: | ---: | ---: |"]
    totals = dict.fromkeys(STATUSES, 0)
    for name, items in areas.items():
        counts = {status: sum(item["status"] == status for item in items) for status in STATUSES}
        for status in STATUSES: totals[status] += counts[status]
        lines.append(f"| {AREAS[name]} | " + " | ".join(str(counts[status]) for status in STATUSES) + f" | {len(items)} |")
    lines.append("| **All** | " + " | ".join(f"**{totals[status]}**" for status in STATUSES) + f" | **{sum(totals.values())}** |")
    for name, items in areas.items():
        lines += ["", f"## {AREAS[name]}", ""]
        for status, heading in (("partial", "Partial"), ("missing", "Missing")):
            chosen = [item for item in items if item["status"] == status]
            if not chosen: continue
            lines += [f"### {heading}", "", "| Feature | Remaining | Offline | Size |", "| --- | --- | :---: | :---: |"]
            for item in chosen:
                lines.append(f"| {cell(item['title'])} (`{item['id']}`) | {cell('; '.join(item['gaps']))} | "
                             f"{'yes' if item.get('offline_feasible') else 'no'} | {item.get('size', '')} |")
            lines.append("")
        done = [item for item in items if item["status"] == "done"]
        if done: lines += ["### Done", "", ", ".join(f"{cell(item['title'])}" for item in done) + ".", ""]
        skipped = [item for item in items if item["status"] == "not_applicable"]
        if skipped:
            lines += ["### Not applicable on PS5", ""]
            lines += [f"- {cell(item['title'])}: {cell(item.get('notes') or item.get('smarttube', ''))}" for item in skipped]
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when docs/PARITY.md is stale")
    args = parser.parse_args()
    text, target = render(load()), ROOT / "docs/PARITY.md"
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text: raise SystemExit("docs/PARITY.md is stale; run scripts/parity_report.py")
    else:
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {target.relative_to(ROOT)}")


if __name__ == "__main__": main()
