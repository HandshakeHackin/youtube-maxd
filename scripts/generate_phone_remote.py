#!/usr/bin/env python3
"""Embed the PS5-served phone page without a runtime filesystem dependency."""
# SPDX-License-Identifier: GPL-3.0-or-later
import json
from pathlib import Path
import argparse
root = Path(__file__).resolve().parents[1]
source = root / 'native/maxd/phone_remote_page.html'
target = source.with_suffix('.h')
expected = '/* Generated by scripts/generate_phone_remote.py. GPL-3.0-or-later. */\nstatic const char maxd_phone_remote_page[]=\n' + '\n'.join(json.dumps(line + '\n', ensure_ascii=True) for line in source.read_text().splitlines()) + ';\n'
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
if p.parse_args().check:
    assert target.read_text() == expected, 'Regenerate the phone remote page'
else:
    target.write_text(expected)
