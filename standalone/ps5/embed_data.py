#!/usr/bin/env python3
"""Turn files into C byte arrays, the way EVO embeds its UI assets
(tools/bundle_rml_assets.py): the app reads them from memory, with no call
into the package's file system.

    embed_data.py OUTPUT.c NAME=FILE [NAME=FILE ...]

Each NAME becomes `const unsigned char NAME[]` (with one zero byte after the
data, not counted) and `const size_t NAME_length`. The matching declarations
go to OUTPUT.h.
SPDX-License-Identifier: GPL-3.0-or-later
"""
import hashlib
import pathlib
import re
import sys


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    output = pathlib.Path(sys.argv[1])
    source = ["/* Generated by standalone/ps5/embed_data.py - do not edit. */", "#include <stddef.h>"]
    header = ["/* Generated by standalone/ps5/embed_data.py - do not edit. */", "#include <stddef.h>",
              "#ifdef __cplusplus", 'extern "C" {', "#endif"]
    for item in sys.argv[2:]:
        name, _, path = item.partition("=")
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) or not path:
            raise SystemExit(f"bad NAME=FILE: {item}")
        data = pathlib.Path(path).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        source.append(f"/* {pathlib.Path(path).name}: {len(data)} bytes, sha256 {digest} */")
        source.append(f"const unsigned char {name}[] = {{")
        for start in range(0, len(data), 24):
            source.append(",".join(str(byte) for byte in data[start:start + 24]) + ",")
        source.append("0};")
        source.append(f"const size_t {name}_length = {len(data)};")
        header.append(f"extern const unsigned char {name}[];")
        header.append(f"extern const size_t {name}_length;")
    header += ["#ifdef __cplusplus", "}", "#endif"]
    output.write_text("\n".join(source) + "\n")
    output.with_suffix(".h").write_text("\n".join(header) + "\n")


if __name__ == "__main__":
    main()
